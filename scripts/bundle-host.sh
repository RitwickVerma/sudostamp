#!/usr/bin/env bash
# Build the single-file host installer, dist/sudostamp-setup.sh, from tools/.
#
#   scripts/bundle-host.sh [VERSION]       (default: versionName from app/build.gradle.kts)
#
# The result is what people download instead of cloning the repository:
#
#   curl -fsSLO <release>/sudostamp-setup.sh && sudo bash sudostamp-setup.sh
#
# It unpacks install.sh and its helpers into a fresh directory, runs install.sh (default
# command: setup), and removes the directory on exit. Nothing else is downloaded except
# pam_rssh itself, exactly as when running from a checkout.
#
# Deterministic: plain concatenation of the files in a fixed order, so anyone can rebuild it
# from the tagged source and compare the SHA-256 with the one published in the release.
set -euo pipefail
cd "$(dirname "$0")/.."

version="${1:-$(sed -n 's/.*versionName = "\(.*\)".*/\1/p' app/build.gradle.kts)}"
[ -n "$version" ] || { echo "no version" >&2; exit 1; }
out=dist/sudostamp-setup.sh
mkdir -p dist

files="tools/install.sh tools/pair.py tools/pam_check.py tools/sudostamp-is-local.sh"
for f in $files; do
  # A file containing its own heredoc terminator would cut the bundle short.
  if grep -q '^SUDOSTAMP_BUNDLE_EOF' "$f"; then echo "$f contains the bundle terminator" >&2; exit 1; fi
done

{
  cat <<HDR
#!/bin/bash
# SudoStamp $version -- host setup, single file. https://gitlab.com/ritwick7/sudostamp
#
#   sudo bash sudostamp-setup.sh            set up: pair with the phone and enable it for sudo
#   sudo bash sudostamp-setup.sh rollback   take it out again
#   bash sudostamp-setup.sh status          what is in place
#
# Generated by scripts/bundle-host.sh from tools/ at this version; do not edit. Rebuild it from
# the tagged source to check it byte for byte, or compare its SHA-256 with the release page.
set -u
[ "\$(id -u)" -eq 0 ] || [ "\${1:-}" = status ] || { echo "Run it with sudo: sudo bash \$0 \$*" >&2; exit 1; }
SUDOSTAMP_BUNDLE_DIR="\$(mktemp -d /tmp/sudostamp-setup.XXXXXXXX)" || exit 1
# Readable, not writable, by others: install.sh reads the gate script as the invoking user.
chmod 0755 "\$SUDOSTAMP_BUNDLE_DIR"
export SUDOSTAMP_BUNDLE_DIR
HDR
  for f in $files; do
    b="$(basename "$f")"
    echo "cat > \"\$SUDOSTAMP_BUNDLE_DIR/$b\" <<'SUDOSTAMP_BUNDLE_EOF'"
    cat "$f"
    echo "SUDOSTAMP_BUNDLE_EOF"
  done
  cat <<'TAIL'
chmod 0755 "$SUDOSTAMP_BUNDLE_DIR"/*
# No command, or only options (`--phone ...`): the command is setup.
case "${1:-}" in ""|-*) set -- setup "$@" ;; esac
SUDOSTAMP_PROG="bash $(basename "$0")" exec bash "$SUDOSTAMP_BUNDLE_DIR/install.sh" "$@"
TAIL
} > "$out"
chmod 0755 "$out"
sha256sum "$out"
